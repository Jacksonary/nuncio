let registered = false;

/** Merge the composer dictionary into the shared i18n store (idempotent). */
export function registerComposeI18n(): void {
  if (registered) return;
  registered = true;
  Object.assign(dictionaries["zh-CN"], composeI18n["zh-CN"]);
  Object.assign(dictionaries["en-US"], composeI18n["en-US"]);
}

registerComposeI18n();
